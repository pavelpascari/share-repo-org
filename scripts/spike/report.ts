/** One observed API interaction. `observed` holds sanitized fields only: never tokens or keys. */
export interface StepResult {
  readonly step: string;
  readonly operation: string;
  readonly status: string;
  readonly observed: Readonly<Record<string, unknown>>;
  readonly interpretation: string;
}

export interface Conclusion {
  readonly question: string;
  readonly answer: string;
}

export interface ReportInput {
  readonly date: string;
  readonly appId: string;
  readonly repository: string;
  readonly subscriber: string;
  readonly steps: readonly StepResult[];
  readonly conclusions: readonly Conclusion[];
  /** The previous file's manual checklist, kept so ticked boxes survive a re-run. */
  readonly existingChecklist: string | null;
}

export const MANUAL_CHECKLIST_HEADING = "## Manual checklist";

export const DEFAULT_MANUAL_CHECKLIST = `${MANUAL_CHECKLIST_HEADING}

Things the script cannot observe. Tick each one and note what you saw.

- [ ] **Invitation email.** The subscriber account received an invitation email for the test repository. Result: …
- [ ] **Member webhook on a personal installation.** Invite the subscriber once by hand on GitHub (repository → Settings → Collaborators) and accept as the subscriber. Then open the App → *Advanced* → *Recent deliveries* and check whether a \`member\` event with action \`added\` arrived. Result: …
- [ ] **Access after acceptance.** The subscriber can push to a non-protected branch (confirms write access, decision 0008). Result: …
- [ ] **Branch protection.** Settings → Branches (or Rules) on the private repository can protect the default branch on your plan. Result: …
- [ ] **Clean-up.** Remove the subscriber again (re-running the spike does this) and confirm any fork they made was deleted. Result: …
`;

const cell = (value: unknown): string =>
  (typeof value === "string" ? value : JSON.stringify(value))
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ");

/** Renders `docs/research/github-live-results.md`. */
export function renderReport(input: ReportInput): string {
  const rows = input.steps.map(
    (step) =>
      `| ${cell(step.step)} | ${cell(step.operation)} | ${cell(step.status)} | ${cell(step.observed)} | ${cell(step.interpretation)} |`,
  );
  const conclusions = input.conclusions.map(
    (conclusion) => `- **${conclusion.question}** ${conclusion.answer}`,
  );
  return [
    "# GitHub live results (personal-account repository)",
    "",
    "> Generated by `pnpm spike:github` (`scripts/spike/github-feasibility.ts`). Re-run the spike rather than editing the generated sections; the manual checklist is kept across runs.",
    "",
    `- **Run:** ${input.date}`,
    `- **App ID:** ${input.appId}`,
    `- **Repository:** \`${input.repository}\``,
    `- **Subscriber account:** \`${input.subscriber}\``,
    "- **Context:** the open questions in [github-personal-accounts.md § Product implications, item 10](github-personal-accounts.md#product-implications) and decision [0008](../decisions/0008-v1-personal-account-repositories.md).",
    "",
    "## Observations",
    "",
    "| Step | Operation | HTTP status | Observed | Interpretation |",
    "|---|---|---|---|---|",
    ...rows,
    "",
    "## Conclusions",
    "",
    ...conclusions,
    "",
    (input.existingChecklist ?? DEFAULT_MANUAL_CHECKLIST).trimEnd(),
    "",
  ].join("\n");
}

/** The manual checklist section of an existing report, or null if there is none. */
export function extractChecklist(markdown: string): string | null {
  const start = markdown.indexOf(MANUAL_CHECKLIST_HEADING);
  return start === -1 ? null : markdown.slice(start).trimEnd();
}
